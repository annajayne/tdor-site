import argparse
import os
import sys

from pathlib import Path

from PowerPointAudioInserter import PowerPointAudioInserter


def run():
    parser = argparse.ArgumentParser(description='This script adds autoplaying audio clips (as generated by SpeakNames) to individual slides in a PowerPoint document')

    parser.add_argument('-i','--input', help = 'The path of the input PowerPoint document', required=True)
    parser.add_argument('-o','--output', help = 'The path of the output PowerPoint document. Requires --input', required=False)

    parser.add_argument('-a','--audio-folder', help = 'The path of a folder containing MP3 audio clips to insert. If not specified, no changes will be made', required=True)
    parser.add_argument('-l','--leave-open',  action="store_true", help = ' Leave PowerPoint open after editing', required=False)

    parser._actions[0].help = 'Show this help message and exit'

    try:
        args = parser.parse_args()
    except:
        exit(0)

    if args.output and os.path.exists(args.output):
        os.remove(args.output)
        print(f"Deleted output document {args.output}")

    if args.input:
        inserter = PowerPointAudioInserter(args.audio_folder)

        inserter.open(args.input)

        if args.output:
            output_path = Path(args.output).resolve()
            if os.path.exists(output_path):
                os.remove(output_path)

            inserter.saveas(output_path)

        if not args.leave_open:
            inserter.close()


if __name__ == "__main__":
    run()
