class VoiceInfo:
    def get_number(self):
        return self.number

    def set_number(self, number):
        self.number = number


    def get_id(self):
        return self.id

    def set_id(self, id):
        self.id = id


    def get_name(self):
        return self.name

    def set_name(self, name):
        self.name = name


    def get_language(self):
        return self.language

    def set_language(self, language):
        self.language = language

